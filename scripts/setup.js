#!/usr/bin/env node
/**
 * Otium — Interactive One-Command Local Setup
 * Dijalankan via: npm run setup
 *
 * Fitur:
 * 1. Membuat file `.env` otomatis (DATABASE_URL aman + JWT_SECRET acak 64-hex).
 * 2. Membuat database PostgreSQL bila belum ada (menggunakan `pg`, tanpa ORM).
 * 3. Mengimpor skema & data awal dari `database/database.sql`.
 * 4. Memastikan direktori unggahan lokal (`public/uploads/*`) tersedia.
 */

const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const readline = require("node:readline/promises");
const { stdin: input, stdout: output } = require("node:process");
const { Client } = require("pg");

const ROOT_DIR = path.resolve(__dirname, "..");
const ENV_PATH = path.join(ROOT_DIR, ".env");
const SQL_PATH = path.join(ROOT_DIR, "database", "database.sql");

const DB_NAME_REGEX = /^[a-zA-Z0-9_]+$/;

async function ask(rl, question, defaultValue = "") {
  const suffix = defaultValue ? ` [${defaultValue}]` : "";
  const answer = (await rl.question(`${question}${suffix}: `)).trim();
  return answer || defaultValue;
}

function buildConnectionString({ host, port, user, password, database }) {
  const encUser = encodeURIComponent(user);
  const encPass = encodeURIComponent(password);
  const auth = password ? `${encUser}:${encPass}` : encUser;
  return `postgresql://${auth}@${host}:${port}/${database}`;
}

function ensureUploadDirs() {
  const dirs = [
    path.join(ROOT_DIR, "public", "uploads"),
    path.join(ROOT_DIR, "public", "uploads", "attachments"),
    path.join(ROOT_DIR, "public", "uploads", "avatars"),
  ];
  for (const dir of dirs) {
    fs.mkdirSync(dir, { recursive: true });
  }
}

async function main() {
  console.log("\n========================================================");
  console.log("  OTIUM — Setup Otomatis Lingkungan Lokal (PostgreSQL)");
  console.log("========================================================\n");

  if (!fs.existsSync(SQL_PATH)) {
    console.error(`[ERROR] File SQL tidak ditemukan: ${SQL_PATH}`);
    process.exit(1);
  }

  const rl = readline.createInterface({ input, output });

  try {
    // 1. Cek apakah .env sudah ada
    let shouldWriteEnv = true;
    if (fs.existsSync(ENV_PATH)) {
      const overwrite = await ask(
        rl,
        "File .env sudah ada. Timpa dengan konfigurasi baru? (y/N)",
        "N"
      );
      shouldWriteEnv = overwrite.toLowerCase() === "y";
    }

    // 2. Kumpulkan kredensial PostgreSQL
    const host = await ask(rl, "PostgreSQL Host", "localhost");
    const portStr = await ask(rl, "PostgreSQL Port", "5432");
    const port = Number(portStr);
    if (!Number.isInteger(port) || port <= 0 || port > 65535) {
      throw new Error("Port PostgreSQL tidak valid.");
    }

    const user = await ask(rl, "PostgreSQL Username", "postgres");
    const password = await ask(rl, "PostgreSQL Password (kosongkan jika tidak ada)", "");
    const database = await ask(rl, "Nama Database Otium", "otium_db");

    if (!DB_NAME_REGEX.test(database)) {
      throw new Error(
        "Nama database hanya boleh berisi huruf, angka, dan underscore (_)."
      );
    }

    const databaseUrl = buildConnectionString({
      host,
      port,
      user,
      password,
      database,
    });

    // 3. Tulis file .env dengan JWT_SECRET acak
    if (shouldWriteEnv) {
      const jwtSecret = crypto.randomBytes(32).toString("hex");
      const envContent = [
        "# Generated by `npm run setup` — Otium",
        `DATABASE_URL="${databaseUrl}"`,
        `JWT_SECRET="${jwtSecret}"`,
        "",
      ].join("\n");
      fs.writeFileSync(ENV_PATH, envContent, { encoding: "utf8" });
      console.log("\n[OK] File .env berhasil dibuat dengan JWT_SECRET acak.");
    } else {
      console.log("\n[SKIP] File .env eksisting dipertahankan.");
    }

    // 4. Pastikan direktori upload lokal tersedia
    ensureUploadDirs();
    console.log("[OK] Direktori public/uploads/ siap digunakan.");

    // 5. Cek & buat database jika belum ada (koneksi ke database 'postgres')
    console.log(`\nMenghubungi PostgreSQL (${host}:${port})...`);
    const adminClient = new Client({
      host,
      port,
      user,
      password: password || undefined,
      database: "postgres",
    });

    await adminClient.connect();
    try {
      const checkRes = await adminClient.query(
        "SELECT 1 FROM pg_database WHERE datname = $1",
        [database]
      );

      if (checkRes.rowCount === 0) {
        await adminClient.query(`CREATE DATABASE "${database}"`);
        console.log(`[OK] Database "${database}" berhasil dibuat.`);
      } else {
        console.log(`[INFO] Database "${database}" sudah tersedia.`);
      }
    } finally {
      await adminClient.end();
    }

    // 6. Konfirmasi & impor database/database.sql (DDL + Seed Data)
    const confirmSeed = await ask(
      rl,
      `Impor skema & data awal ke "${database}"? (PERINGATAN: tabel lama di "${database}" akan di-reset) (Y/n)`,
      "Y"
    );

    if (confirmSeed.toLowerCase() === "y") {
      const sqlScript = fs.readFileSync(SQL_PATH, "utf8");
      const targetClient = new Client({
        host,
        port,
        user,
        password: password || undefined,
        database,
      });

      await targetClient.connect();
      try {
        await targetClient.query(sqlScript);
        console.log(
          "[OK] Skema 7 tabel & data awal (database/database.sql) berhasil diimpor."
        );
      } finally {
        await targetClient.end();
      }
    } else {
      console.log("[SKIP] Impor database/database.sql dilewati.");
    }

    // 7. Ringkasan selesai
    console.log("\n========================================================");
    console.log("  SETUP SELESAI! Jalankan aplikasi dengan:");
    console.log("    npm run dev");
    console.log("  Lalu buka: http://localhost:3000/login");
    console.log("--------------------------------------------------------");
    console.log("  Akun Demo Awal (Password: password123):");
    console.log("    - Admin        : admin@perusahaan.com      (admin)");
    console.log("    - HRD          : hrd@perusahaan.com        (hrd)");
    console.log("    - Ketua Divisi : ketua.eng@perusahaan.com  (leader.eng)");
    console.log("    - Karyawan 1   : andi.pratama@perusahaan.com (karyawan1)");
    console.log("    - Karyawan 2   : dewi.lestari@perusahaan.com (karyawan2)");
    console.log("========================================================\n");
  } catch (error) {
    console.error(`\n[ERROR] Setup gagal: ${error.message}`);
    console.error(
      "Pastikan layanan PostgreSQL aktif dan kredensial yang dimasukkan benar.\n"
    );
    process.exitCode = 1;
  } finally {
    rl.close();
  }
}

main();
